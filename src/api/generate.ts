import { estimateCost } from "../lib/costTracker";
import { chooseProvider, type RouteRequest } from "../lib/modelRouter";
import { resolveTimeout } from "../lib/timeouts";

export type GenerationResponse = {
  providerId: string;
  text: string;
  estimatedCost: number;
  timeoutMs: number;
};

export async function generate(request: RouteRequest): Promise<GenerationResponse> {
  const decision = chooseProvider(request);
  const timeoutMs = resolveTimeout({
    providerId: decision.provider.id,
    overrideMs: request.timeoutMs,
  });

  return {
    providerId: decision.provider.id,
    timeoutMs,
    text: `Slop generated by ${decision.provider.name}`,
    estimatedCost: estimateCost({
      inputTokens: request.prompt.length / 4,
      outputTokens: 420,
      costPerMillionTokens: decision.provider.costPerMillionTokens,
    }),
  };
}
